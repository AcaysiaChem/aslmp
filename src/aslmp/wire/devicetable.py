from aslmp.wire.citations import Citation, Measurement, Provenance, Source
from aslmp.wire.codec import SpecFormat, Unit

__all__ = ["DEVICE_TABLE", "PREFIXES_LONGEST_FIRST", "DeviceType", "Radix"]


class Radix(enum.IntEnum):
    """The base a device NUMBER is written in. The value is the base, so
    ``int(text, Radix.OCTAL)`` parses an iQ-F X/Y literal directly."""

    OCTAL = 8
    DECIMAL = 10
    HEXADECIMAL = 16


@dataclass(frozen=True, slots=True)
class DeviceType:
    """One device family: how it is named, how it is coded, and where it may be used."""

    name: str
    long_name: str
    unit: Unit
    words_per_point: int
    ascii2: str
    ascii4: str
    code_short: int | None
    code_long: int
    radix: Radix
    min_spec: SpecFormat
    batch_ok: bool
    random_ok: bool
    monitor_ok: bool
    block_ok: bool
    provenance: Provenance
    citation: Citation | None
    measurement: Measurement | None
    note: str

    @property
    def source(self) -> Source:
        """The authoritative provenance: the measurement if there is one."""
        if self.measurement is not None:
            return self.measurement
        if self.citation is None:
            raise ValueError(f"device {self.name} has neither a citation nor a measurement")
        return self.citation


